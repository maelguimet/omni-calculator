#!/usr/bin/env python3
"""Create deterministic, source-grounded local Needle training examples.

No teacher model, network, or personal data. The held-out set uses different
phrase templates and numeric ranges. Explicit calculator expressions are
referenced through evaluate() and therefore never regenerated by the model.
"""

import argparse
import collections
import hashlib
import json
import pathlib
import random

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOOLS = json.loads((ROOT / "experiments/tools.json").read_text())
SYSTEM = (ROOT / "experiments/system.txt").read_text().strip()


def number(rng, heldout=False, positive=False):
    if heldout:
        value = rng.randint(103, 499)
    else:
        value = rng.randint(1, 97)
    if not positive and rng.random() < 0.2:
        value = -value
    if rng.random() < 0.15:
        return str(value / 10)
    return str(value)


def phrase(rng, heldout, ordinary, novel, **values):
    return rng.choice(novel if heldout else ordinary).format(**values)


def row(query, tool=None, args=None, family="", reasoning=""):
    return {"query": query, "tools": TOOLS, "system": SYSTEM,
            "answers": [{"name": tool, "arguments": args or {}}] if tool else [],
            "reasoning": reasoning or ("Read the source expression." if tool == "evaluate"
                                        else "No calculator request." if not tool
                                        else f"Use {tool} with the source values."),
            "_family": family}


def raw(rng, heldout):
    shape = rng.randrange(9)
    a, b, c = (number(rng, heldout) for _ in range(3))
    if rng.random() < 0.35:
        a, b, c = (str(rng.randint(0, 9)) for _ in range(3))
    if shape == 0:
        expression = rng.choice([a, "pi", "e", "i", "tau", f"{a}e-{rng.randint(1,12)}"])
    elif shape == 1:
        expression = a + rng.choice(["+", "-", "*", "/", "^"]) + b
    elif shape == 2:
        expression = a + rng.choice(["+", "-"]) + b + rng.choice(["*", "/", "^"]) + c
    elif shape == 3:
        expression = f"{rng.choice(['sqrt','sin','cos','ln','abs','exp','cbrt'])}({a})"
    elif shape == 4:
        expression = f"{a} {rng.choice(['km to miles','meters to feet','kg to pounds','fahrenheit to celsius','degrees to radians'])}"
    elif shape == 5:
        vector = f"[{a},{b},{c}]"
        expression = rng.choice([f"mean({vector})", f"sum({vector})", f"median({vector})", f"det([[{a},{b}],[{c},1]])",
                                 f"diff(x^{rng.randint(1,9)},x)", f"integrate(x^{rng.randint(1,9)},x,0,{a})"])
    elif shape == 6:
        # Refer incomplete explicit inputs unchanged; Rust owns their errors.
        expression = rng.choice([f"{a}+", f"({a}+{b}", f"sin({a}", f"sqrt(", f"{a}/0", f"{a}**", f"({a}]"])
    else:
        depth = rng.randint(3, 5) if heldout else rng.randint(1, 3)
        expression = a
        for _ in range(depth):
            op = rng.choice(["+", "-", "*", "/", "^"])
            expression = f"({expression}{op}{number(rng, heldout, positive=True)})"
        if rng.random() < 0.4:
            expression = f"{rng.choice(['sqrt','sin','cos','ln','abs','exp'])}({expression})"
    if rng.random() < 0.2:
        # Spaces around operators are syntax-preserving, including signs.
        expression = expression.replace("+", " + ").replace("*", " * ").replace("/", " / ")
    query = phrase(rng, heldout,
                   ["{e}", "what is {e}", "calculate {e}", "wat iz {e}", "what's {e}?", "evaluate {e}"],
                   ["please calculate {e}", "could you evaluate {e}", "compute {e}", "wht is {e}?"], e=expression)
    return row(query, "evaluate", family="explicit")


UNARY = {
    "sqrt": ["square root", "sqrt", "squre root"], "cbrt": ["cube root", "cubic root"],
    "sin": ["sine", "sin"], "cos": ["cosine", "cos"], "tan": ["tangent", "tan"],
    "asin": ["arcsine", "inverse sine"], "acos": ["arccosine", "inverse cosine"],
    "atan": ["arctangent", "inverse tangent"], "sinh": ["hyperbolic sine", "sinh"],
    "cosh": ["hyperbolic cosine", "cosh"], "tanh": ["hyperbolic tangent", "tanh"],
    "exp": ["exponential", "exp"], "ln": ["natural logarithm", "natural log"],
    "factorial": ["factorial"], "abs": ["absolute value", "magnitude"],
}


def unary(rng, heldout):
    operation = rng.choice(list(UNARY))
    label = rng.choice(UNARY[operation])
    argument = number(rng, heldout)
    if operation in ("asin", "acos"):
        argument = str(rng.randint(-99, 99) / 100)
    elif operation == "factorial":
        argument = str(rng.randint(1, 80))
    elif operation in ("sin", "cos", "tan") and rng.random() < 0.35:
        argument += " degrees"
    elif rng.random() < 0.18:
        argument = f"({argument}+{number(rng, heldout)})"
    if operation not in ("factorial", "asin", "acos") and rng.random() < 0.25:
        argument = rng.choice(["pi", "e", f"pi/{rng.randint(2,12)}", f"e^{rng.randint(1,9)}", f"({number(rng,heldout)}*pi)"])
    query = phrase(rng, heldout,
                   ["{op} of {a}", "calculate the {op} of {a}", "what is the {op} of {a}?", "find {op} of {a}"],
                   ["please give me the {op} for {a}", "I need the {op} of {a}", "compute {op} for {a}"],
                   op=label, a=argument)
    return row(query, "function", {"function": operation, "arguments": [argument]},
               "unary", f"{label} means {operation}; use {argument}.")


